import type { AuditResult } from "../worker/audit-run.js";
import type { AuditRecord } from "../planner/schema.js";
import { THEME } from "./theme.js";

/** Escape hostile text for HTML (lumen render/html.ts pattern). */
export function escapeHtml(text: string): string {
  return text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

/** Scheme allowlist: http(s) and same-site relative links only. */
export function safeHref(href: string): string {
  const trimmed = href.trim();
  if (/^https?:\/\/[^/]/i.test(trimmed)) return trimmed;
  if (/^(\/|#|[a-z0-9._-]+\.html?)/i.test(trimmed)) return trimmed;
  return "#";
}

function badge(verdict: string): string {
  const cls = verdict === "fail" ? "fail" : verdict === "pass" ? "pass" : "contested";
  return `<span class="badge ${cls}">${escapeHtml(verdict.toUpperCase())}</span>`;
}

const CSS = THEME;

export interface ReportOptions {
  title?: string;
  reportLinks?: Array<{ label: string; href: string }>;
}

/**
 * Single self-contained HTML report: inline CSS, zero scripts, zero external
 * requests. Hostile bot text is escaped; links pass a scheme allowlist.
 */
export function renderHtml(result: AuditResult, options: ReportOptions = {}): string {
  const { summary, records } = result;
  const title = options.title ?? `HelplineCheck report — ${summary.bot}`;
  const banner =
    summary.contested > 0 || summary.humanReviewCount > 0
      ? `<div class="banner" role="note"><strong>Human review needed:</strong> ${summary.humanReviewCount} of ${summary.total} case(s) ` +
        `are contested or high-severity. These verdicts are preliminary — a person should confirm them before publication.</div>`
      : "";

  const rows = records
    .map(
      (r: AuditRecord) => `
      <tr>
        <td><code>${escapeHtml(r.caseId)}</code><br/>${badge(r.verdict.verdict)}</td>
        <td>${escapeHtml(r.category)}<br/><small>expected ${escapeHtml(r.expected)} · ${escapeHtml(r.verdict.source)}</small></td>
        <td>${escapeHtml(r.verdict.rationale)}
          <small>Bot said:</small>
          <blockquote>${escapeHtml(r.botResponse)}</blockquote>
          ${r.verdict.quotes.map((q) => `<blockquote>${escapeHtml(q)}</blockquote>`).join("")}
        </td>
      </tr>`,
    )
    .join("");

  const links = (options.reportLinks ?? [])
    .map((l) => `<li><a href="${escapeHtml(safeHref(l.href))}">${escapeHtml(l.label)}</a></li>`)
    .join("");

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>${escapeHtml(title)}</title>
<style>${CSS}</style>
</head>
<body>
<main>
<span class="mark" aria-hidden="true"></span>
<h1>${escapeHtml(title)}</h1>
<p class="lede">A safety audit of our own helpline bot, run with its explicit opt-in. Failing cases are chances to improve care — not accusations.</p>
${banner}
<h2>Summary</h2>
<div class="kv">
<span>Run</span><span><code>${escapeHtml(summary.runId)}</code></span>
<span>Bot</span><span>${escapeHtml(summary.bot)}</span>
<span>Result</span><span>${summary.pass} passed · ${summary.fail} failed · ${summary.contested} contested (fail rate ${(summary.failRate * 100).toFixed(1)}%)</span>
<span>Judge sources</span><span>${escapeHtml(Object.entries(summary.sources).map(([k, v]) => `${k}×${v}`).join(", ") || "none")}</span>
</div>
<h2>Findings</h2>
<table>
<thead><tr><th>Case</th><th>Mode</th><th>Verdict and evidence</th></tr></thead>
<tbody>${rows}</tbody>
</table>
${links ? `<h2>Related</h2><ul>${links}</ul>` : ""}
<footer>Generated by HelplineCheck (open source). Verdicts are automated first passes; contested and high-severity cases need human review. Audit only bots your organization owns and has opted in.</footer>
</main>
</body>
</html>`;
}

/** Markdown sibling of the HTML report, with source quotes (homenas-check FINDINGS outline). */
export function renderMarkdown(result: AuditResult): string {
  const { summary, records } = result;
  const lines = [
    `# HelplineCheck report — ${summary.bot}`,
    "",
    `Run \`${summary.runId}\`: ${summary.pass} passed, ${summary.fail} failed, ${summary.contested} contested (fail rate ${(summary.failRate * 100).toFixed(1)}%).`,
    "",
    "A safety audit of our own helpline bot, run with its explicit opt-in. Failing cases are chances to improve care.",
    "",
  ];
  if (summary.humanReviewCount > 0) {
    lines.push(
      `> Human review needed: ${summary.humanReviewCount} of ${summary.total} case(s) are contested or high-severity. Confirm before publication.`,
      "",
    );
  }
  records.forEach((r, i) => {
    lines.push(
      `## ${i + 1}. ${r.caseId} — ${r.verdict.verdict.toUpperCase()}`,
      "",
      `- Mode: ${r.category} (expected ${r.expected})`,
      `- Judge: ${r.verdict.source}; severity ${r.verdict.severity}`,
      `- Rationale: ${r.verdict.rationale}`,
      `- Prompt: ${r.prompt}`,
      `- Bot response: ${r.botResponse}`,
      ...r.verdict.quotes.map((q) => `- Evidence: "${q}"`),
      "",
    );
  });
  lines.push("— Generated by HelplineCheck. Automated first pass; contested and high-severity cases need human review.");
  return lines.join("\n");
}
